function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function when(day, hour, dur) {
  const s = new Date();
  s.setDate(s.getDate() + day);
  s.setHours(hour, 0, 0, 0);
  return [localIso(s), localIso(new Date(s.getTime() + dur * 3600e3))];
}

